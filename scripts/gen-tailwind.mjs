import { readFileSync, writeFileSync } from "node:fs";

const [colorsPath, dimsPath] = process.argv.slice(2);
if (!colorsPath || !dimsPath) {
  console.error("Usage: node scripts/gen-tailwind.mjs <colors.tokens.json> <dimensions.tokens.json>");
  process.exit(1);
}
const colors = JSON.parse(readFileSync(colorsPath, "utf8"));
const dims = JSON.parse(readFileSync(dimsPath, "utf8"));

const colorOut = {};
for (const [group, node] of Object.entries(colors)) {
  if (group.startsWith("$")) continue;
  const g = group.toLowerCase();
  if (node.$type === "color") { colorOut[g] = node.$value.hex.toLowerCase(); continue; }
  for (const [shade, tok] of Object.entries(node)) colorOut[`${g}-${shade}`] = tok.$value.hex.toLowerCase();
}

const keyOf = (k) => k.replace(/\u2024/g, ".");
const radius = {};
for (const [k, tok] of Object.entries(dims["Border Radius"])) {
  const name = k === "rounded" ? "default" : k.replace(/^rounded-/, "");
  radius[name] = tok.$value;
}
const spacing = {};
for (const [k, tok] of Object.entries(dims["Spacing"])) spacing[keyOf(k)] = tok.$value;
const screens = {};
for (const [k, tok] of Object.entries(dims["Screens"])) screens[k] = tok.$value;

const out = `// Generated by scripts/gen-tailwind.mjs. Do not edit by hand.
export const TAILWIND_COLORS: Record<string, string> = ${JSON.stringify(colorOut, null, 2)};

export const TAILWIND_RADIUS: Record<string, number> = ${JSON.stringify(radius, null, 2)};

export const TAILWIND_SPACING: Record<string, number> = ${JSON.stringify(spacing, null, 2)};

export const TAILWIND_SCREENS: Record<string, number> = ${JSON.stringify(screens, null, 2)};
`;
writeFileSync("src/core/systems/tailwind.data.ts", out);
console.log(`colors=${Object.keys(colorOut).length} radius=${Object.keys(radius).length} spacing=${Object.keys(spacing).length} screens=${Object.keys(screens).length}`);
