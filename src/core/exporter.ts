import { isDark } from "./color";
import { SCHEMA, SCHEMA_VERSION } from "./schema";
import type { ThemeInfo } from "./themes";

export function toSaiderJson(theme: ThemeInfo, system: string): string {
  const out: Record<string, string | number> = { $saider: SCHEMA_VERSION, name: theme.name, system };
  for (const def of SCHEMA.tokens) {
    const ref = theme.values[def.key]?.ref;
    if (ref !== undefined) out[def.key] = ref;
  }
  return JSON.stringify(out, null, 2) + "\n";
}

const cssValue = (kind: string, key: string, value: string | number) => {
  if (kind === "color") return String(value);
  if (key === "border") return `${value}px`;
  const n = Number(value);
  if (n >= 9999) return "9999px";
  return n === 0 ? "0" : `${+(n / 16).toFixed(4)}rem`;
};

export function toCss(themes: ThemeInfo[]): string {
  const blocks = themes.map((t) => {
    const lines: string[] = [];
    const base = t.values["base-100"]?.value;
    if (typeof base === "string") lines.push(`  color-scheme: ${isDark(base) ? "dark" : "light"};`);
    for (const def of SCHEMA.tokens) {
      const v = t.values[def.key]?.value;
      if (v === undefined) continue;
      lines.push(`  --${def.figmaName.replace(/\//g, "-")}: ${cssValue(def.kind, def.key, v)};`);
    }
    const selector = (t.isDefault ? ":root,\n" : "") + `[data-theme="${t.name}"]`;
    return `${selector} {\n${lines.join("\n")}\n}`;
  });
  return `/* Generated by Saider Theme Builder · format v${SCHEMA_VERSION} */\n\n${blocks.join("\n\n")}\n`;
}
